import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
import numpy as np
import pandas as pd
from scipy.stats import binomtest

from common import RESULTS
from stats import dsp_partial, qap_spearman

N_PERM = 9999


def p5_asymmetry(a):
    """Unordered pairs: does the direction with lower yield-range coverage have the larger level loss?"""
    key = a.set_index(["src", "tgt"])
    wins = n = 0
    for (s, t) in key.index:
        if s > t:
            continue
        c_st, c_ts = key.loc[(s, t), "yield_range_cover"], key.loc[(t, s), "yield_range_cover"]
        if c_st == c_ts:
            continue
        lo, hi = ((s, t), (t, s)) if c_st < c_ts else ((t, s), (s, t))
        n += 1
        wins += key.loc[lo, "loss_level"] > key.loc[hi, "loss_level"]
    return dict(share=wins / n, wins=int(wins), n=int(n),
                p_one_sided=float(binomtest(int(wins), n, 0.5, alternative="greater").pvalue),
                supported=bool(wins / n >= 2 / 3))


def arm_tests(a):
    r = {}
    rho, p = qap_spearman(a, "sub_cover", "loss_rank", N_PERM)
    r["P2_sub_cover_vs_loss_rank"] = dict(rho=rho, p_qap=p, supported=bool(rho < 0 and p < 0.05))
    coef, t, p = dsp_partial(a, "sub_cover", "loss_rank", ["gdd_dist", "geo_km"], fe=True, n_perm=N_PERM)
    rho_g, p_g = qap_spearman(a, "gdd_dist", "loss_rank", N_PERM)
    r["P3_partial"] = dict(std_coef=coef, t=t, p_dsp_qap=p, rho_gdd=rho_g, p_gdd=p_g,
                           supported=bool(coef < 0 and p < 0.05 and abs(rho) > abs(rho_g)))
    rho_l, p_l = qap_spearman(a, "sub_cover", "loss_level", N_PERM)
    r["P4_rank_vs_level"] = dict(rho_rank=rho, rho_level=rho_l, p_level=p_l,
                                 supported=bool(abs(rho) > abs(rho_l)))
    r["P5_asymmetry"] = p5_asymmetry(a)
    # secondary, not pre-registered as hypotheses: every predictor against every loss
    sec = {}
    for x in ["sub_cover", "sub_auc", "full_auc", "full_cover", "full_share2s", "knn_cover",
              "gdd_dist", "geo_km", "log_n_src"]:
        for y in ["loss_rank", "loss_total", "loss_level"]:
            rr, pp = qap_spearman(a, x, y, 1999)
            sec[f"{x}~{y}"] = dict(rho=rr, p_qap=pp)
    r["secondary_rho"] = sec
    r["descriptives"] = {c: dict(median=float(a[c].median()), p10=float(a[c].quantile(.1)),
                                 p90=float(a[c].quantile(.9)))
                         for c in ["R2", "R2_level", "R2_oracle", "loss_total", "loss_level", "loss_rank",
                                   "full_auc", "full_cover", "sub_auc", "sub_cover", "knn_cover"]}
    r["share_pairs_full_auc_ge_0.99"] = float(np.mean(a.full_auc >= 0.99))
    return r


def cross_arm(pairs, arm_a="AEF", arm_b="RS-noclim"):
    A = pairs[pairs.arm == arm_a].set_index(["src", "tgt"])
    B = pairs[pairs.arm == arm_b].set_index(["src", "tgt"]).loc[A.index]
    p1 = {m: float(np.mean(A[m] < B[m])) for m in ["sub_cover", "full_cover", "knn_cover"]}
    p1["full_auc_higher_for_AEF"] = float(np.mean(A.full_auc > B.full_auc))
    d = pd.DataFrame({"src": A.index.get_level_values(0), "tgt": A.index.get_level_values(1),
                      "d_loss": (A.loss_rank - B.loss_rank).values, "d_cov": (A.sub_cover - B.sub_cover).values})
    rho, p = qap_spearman(d, "d_cov", "d_loss", N_PERM)
    return dict(P1_share_pairs_AEF_lower=p1, P1_supported=bool(p1["sub_cover"] >= 2 / 3 and p1["full_cover"] >= 2 / 3),
                P6_rho=rho, P6_p_qap=p, P6_supported=bool(rho < 0 and p < 0.05))


def main():
    pairs = pd.read_csv(RESULTS / "pairs.csv")
    res = {arm: arm_tests(pairs[pairs.arm == arm].reset_index(drop=True)) for arm in pairs.arm.unique()}
    if "RS-noclim" in set(pairs.arm):
        res["cross_arm_AEF_vs_RSnoclim"] = cross_arm(pairs)
    (RESULTS / "tests.json").write_text(json.dumps(res, indent=2))

    L = ["# Results summary (auto-generated by src/run_tests.py)\n"]
    for arm, r in res.items():
        if arm.startswith("cross"):
            L.append(f"## {arm}\n```\n{json.dumps(r, indent=2)}\n```\n")
            continue
        P2, P3, P4, P5 = r["P2_sub_cover_vs_loss_rank"], r["P3_partial"], r["P4_rank_vs_level"], r["P5_asymmetry"]
        L.append(f"## {arm}\n"
                 f"- Full-space separability: {r['share_pairs_full_auc_ge_0.99']:.0%} of pairs with domain AUC >= 0.99\n"
                 f"- P2 rho(sub_cover, loss_rank) = {P2['rho']:.2f}, QAP p = {P2['p_qap']:.4f} -> "
                 f"{'SUPPORTED' if P2['supported'] else 'NOT supported'}\n"
                 f"- P3 partial (GDD, distance, src/tgt FE): std coef {P3['std_coef']:.2f}, DSP-QAP p = {P3['p_dsp_qap']:.4f}; "
                 f"rho(GDD dist, loss_rank) = {P3['rho_gdd']:.2f} -> {'SUPPORTED' if P3['supported'] else 'NOT supported'}\n"
                 f"- P4 |rho rank| {abs(P4['rho_rank']):.2f} vs |rho level| {abs(P4['rho_level']):.2f} -> "
                 f"{'SUPPORTED' if P4['supported'] else 'NOT supported'}\n"
                 f"- P5 lower-coverage direction has larger level loss in {P5['wins']}/{P5['n']} pairs "
                 f"({P5['share']:.0%}), sign-test p = {P5['p_one_sided']:.4f} -> {'SUPPORTED' if P5['supported'] else 'NOT supported'}\n")
    (RESULTS / "summary.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
